#!/usr/bin/env python3
"""Build the master Excel workbook:
outputs/excel/EvalBot_JAIR_PRISMA_Review_Workbook.xlsx

19 sheets, frozen header row, autofilter on data sheets, and data-validation
dropdown lists on decision columns. Populates from whatever CSV/JSON outputs
already exist (all optional — sheets are created with headers even if the
underlying source is empty or missing).

Local-file-only, no network calls.

Usage:
    python scripts/11_generate_excel_workbook.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import (  # noqa: E402
    OUTPUTS_DIR,
    OUTPUTS_EXCEL,
    OUTPUTS_CSV,
    OUTPUTS_PRISMA,
    OUTPUTS_CORPUS,
    DATA_MANUAL,
    read_csv_rows,
    master_records_fieldnames,
    evidence_extraction_fieldnames,
    load_yaml,
)

import openpyxl
from openpyxl.worksheet.worksheet import Worksheet
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

DECISION_VALUES = ["include", "exclude", "unclear", "pending"]
AI_STATUS_VALUES = ["AI draft", "AI draft—human decision pending", "human approved"]

SHEET_NAMES = [
    "README",
    "Protocol",
    "Search_Log",
    "Raw_Records",
    "Deduplication_Audit",
    "Venue_Quality_Verification",
    "Title_Abstract_Screening",
    "Full_Text_Eligibility",
    "Included_Studies",
    "Evidence_Extraction",
    "Quality_Appraisal",
    "OA_Corpus_Manifest",
    "PRISMA_Counts",
    "Review_Exemplars",
    "Manual_Review_Queue",
    "Integrity_Audit",
    "JAIR_Positioning",
    "Target_Journal_Candidates",
    "Submission_Readiness_Checklist",
]


def write_header(ws: Worksheet, headers: list[str]) -> None:
    for col_idx, header in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = Font(bold=True)
    ws.freeze_panes = "A2"
    if headers:
        last_col = get_column_letter(len(headers))
        ws.auto_filter.ref = f"A1:{last_col}1"


def write_rows(ws: Worksheet, headers: list[str], rows: list[dict]) -> None:
    for row_idx, row in enumerate(rows, start=2):
        for col_idx, header in enumerate(headers, start=1):
            ws.cell(row=row_idx, column=col_idx, value=row.get(header, ""))


def add_dropdown(ws: Worksheet, headers: list[str], column_name: str, values: list[str], max_rows: int = 5000) -> None:
    if column_name not in headers:
        return
    col_idx = headers.index(column_name) + 1
    col_letter = get_column_letter(col_idx)
    dv = DataValidation(
        type="list",
        formula1='"{}"'.format(",".join(values)),
        allow_blank=True,
        showDropDown=False,
    )
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}2:{col_letter}{max_rows}")


def build_readme_sheet(ws: Worksheet) -> None:
    ws.append(["EvalBot JAIR PRISMA Review Workbook"])
    ws["A1"].font = Font(bold=True, size=14)
    ws.append([])
    ws.append(["Generated by scripts/11_generate_excel_workbook.py (Phase 0 build)."])
    ws.append(["This workbook is regenerated from the CSV/JSON outputs in outputs/ "
               "and data/manual/ — do not hand-edit generated sheets; edit the "
               "source CSVs or re-run the pipeline scripts instead."])
    ws.append([])
    ws.append(["Sheet", "Source"])
    ws["A6"].font = Font(bold=True)
    ws["B6"].font = Font(bold=True)
    sources = {
        "Protocol": "config/protocol.yaml",
        "Search_Log": "config/search_queries.yaml",
        "Raw_Records": "outputs/csv/master_records.csv",
        "Deduplication_Audit": "outputs/csv/master_records.csv (deduplication_status)",
        "Venue_Quality_Verification": "data/processed/venue_quality_lookup.csv",
        "Title_Abstract_Screening": "outputs/csv/title_abstract_screening_worklist.csv",
        "Full_Text_Eligibility": "outputs/csv/fulltext_eligibility_worklist.csv",
        "Included_Studies": "outputs/csv/master_records.csv (final_included=True)",
        "Evidence_Extraction": "outputs/csv/evidence_extraction.csv",
        "Quality_Appraisal": "outputs/csv/quality_appraisal.csv",
        "OA_Corpus_Manifest": "outputs/corpus/corpus_manifest.csv",
        "PRISMA_Counts": "outputs/prisma/prisma_flow_counts.json",
        "Review_Exemplars": "outputs/csv/systematic_review_exemplars.csv",
        "Manual_Review_Queue": "data/manual/dedup_manual_review_queue.csv",
        "Integrity_Audit": "outputs/logs/errors.csv + integrity audit run",
        "JAIR_Positioning": "outputs/jair_presubmission/*.md",
        "Target_Journal_Candidates": "manual/curated",
        "Submission_Readiness_Checklist": "manual/curated",
    }
    for name, source in sources.items():
        ws.append([name, source])


def build_protocol_sheet(ws: Worksheet) -> None:
    try:
        protocol = load_yaml("protocol.yaml")
    except FileNotFoundError:
        protocol = {}
    write_header(ws, ["field", "value"])
    row = 2
    def flatten(prefix: str, obj) -> None:
        nonlocal row
        if isinstance(obj, dict):
            for k, v in obj.items():
                flatten(f"{prefix}.{k}" if prefix else k, v)
        elif isinstance(obj, list):
            ws.cell(row=row, column=1, value=prefix)
            ws.cell(row=row, column=2, value="; ".join(str(x) for x in obj))
            row += 1
        else:
            ws.cell(row=row, column=1, value=prefix)
            ws.cell(row=row, column=2, value=str(obj))
            row += 1
    flatten("", protocol)


def build_search_log_sheet(ws: Worksheet) -> None:
    try:
        cfg = load_yaml("search_queries.yaml")
    except FileNotFoundError:
        cfg = {}
    headers = ["query_id", "database", "concept_family", "query_type", "query_text", "export_target"]
    write_header(ws, headers)
    rows = []
    for q in cfg.get("queries", []):
        rows.append({
            "query_id": q.get("query_id", ""),
            "database": q.get("database", ""),
            "concept_family": str(q.get("concept_family", "")),
            "query_type": q.get("query_type", ""),
            "query_text": str(q.get("query_text", "")).strip(),
            "export_target": q.get("export_target", ""),
        })
    write_rows(ws, headers, rows)


def build_csv_sheet(ws: Worksheet, csv_path: Path, headers: list[str] | None = None) -> list[str]:
    rows = read_csv_rows(csv_path)
    if headers is None:
        headers = list(rows[0].keys()) if rows else []
    write_header(ws, headers)
    write_rows(ws, headers, rows)
    return headers


def build_prisma_counts_sheet(ws: Worksheet, json_path: Path) -> None:
    write_header(ws, ["metric", "value"])
    if not json_path.exists():
        return
    data = json.loads(json_path.read_text(encoding="utf-8"))
    row = 2
    def flatten(prefix: str, obj) -> None:
        nonlocal row
        if isinstance(obj, dict):
            for k, v in obj.items():
                flatten(f"{prefix}.{k}" if prefix else k, v)
        else:
            ws.cell(row=row, column=1, value=prefix)
            ws.cell(row=row, column=2, value=str(obj))
            row += 1
    flatten("", data)


def build_placeholder_sheet(ws: Worksheet, headers: list[str], note: str) -> None:
    write_header(ws, headers)
    if note:
        ws.cell(row=2, column=1, value=note)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=str(OUTPUTS_EXCEL / "EvalBot_JAIR_PRISMA_Review_Workbook.xlsx"))
    args = parser.parse_args()

    wb = openpyxl.Workbook()
    default_sheet = wb.active
    default_sheet.title = SHEET_NAMES[0]

    for name in SHEET_NAMES[1:]:
        wb.create_sheet(title=name)

    build_readme_sheet(wb["README"])
    build_protocol_sheet(wb["Protocol"])
    build_search_log_sheet(wb["Search_Log"])

    raw_headers = build_csv_sheet(wb["Raw_Records"], OUTPUTS_CSV / "master_records.csv", master_records_fieldnames())
    add_dropdown(wb["Raw_Records"], raw_headers, "title_abstract_human_decision", DECISION_VALUES)
    add_dropdown(wb["Raw_Records"], raw_headers, "fulltext_human_decision", DECISION_VALUES)

    dedup_rows = [r for r in read_csv_rows(OUTPUTS_CSV / "master_records.csv")
                  if r.get("deduplication_status") in ("duplicate", "needs_manual_review")]
    dedup_headers = ["record_id", "title", "doi_normalized", "deduplication_status",
                      "duplicate_of_record_id", "notes"]
    write_header(wb["Deduplication_Audit"], dedup_headers)
    write_rows(wb["Deduplication_Audit"], dedup_headers, dedup_rows)

    build_csv_sheet(wb["Venue_Quality_Verification"], Path("data/processed/venue_quality_lookup.csv"))

    ta_headers = build_csv_sheet(wb["Title_Abstract_Screening"], OUTPUTS_CSV / "title_abstract_screening_worklist.csv")
    add_dropdown(wb["Title_Abstract_Screening"], ta_headers, "title_abstract_human_decision", DECISION_VALUES)
    add_dropdown(wb["Title_Abstract_Screening"], ta_headers, "title_abstract_ai_decision", DECISION_VALUES)

    ft_headers = build_csv_sheet(wb["Full_Text_Eligibility"], OUTPUTS_CSV / "fulltext_eligibility_worklist.csv")
    add_dropdown(wb["Full_Text_Eligibility"], ft_headers, "fulltext_human_decision", DECISION_VALUES)
    add_dropdown(wb["Full_Text_Eligibility"], ft_headers, "fulltext_ai_decision", DECISION_VALUES)

    included_rows = [r for r in read_csv_rows(OUTPUTS_CSV / "master_records.csv")
                      if str(r.get("final_included")).lower() == "true"]
    write_header(wb["Included_Studies"], master_records_fieldnames())
    write_rows(wb["Included_Studies"], master_records_fieldnames(), included_rows)

    build_csv_sheet(wb["Evidence_Extraction"], OUTPUTS_CSV / "evidence_extraction.csv", evidence_extraction_fieldnames())

    qa_headers = ["record_id", "dimension", "rating", "evidence_note"]
    build_placeholder_sheet(wb["Quality_Appraisal"], qa_headers,
                             "Populated by Phase 5 quality appraisal (draft_only, human sign-off required).")
    qa_rows = read_csv_rows(OUTPUTS_CSV / "quality_appraisal.csv")
    if qa_rows:
        qa_headers = list(qa_rows[0].keys())
        write_header(wb["Quality_Appraisal"], qa_headers)
        write_rows(wb["Quality_Appraisal"], qa_headers, qa_rows)

    build_csv_sheet(wb["OA_Corpus_Manifest"], OUTPUTS_CORPUS / "corpus_manifest.csv")

    build_prisma_counts_sheet(wb["PRISMA_Counts"], OUTPUTS_PRISMA / "prisma_flow_counts.json")

    build_csv_sheet(wb["Review_Exemplars"], OUTPUTS_CSV / "systematic_review_exemplars.csv",
                     ["doi", "title", "authors", "journal", "year", "relevance_note", "verified"])

    build_csv_sheet(wb["Manual_Review_Queue"], DATA_MANUAL / "dedup_manual_review_queue.csv")

    audit_headers = ["check", "status", "detail"]
    build_placeholder_sheet(wb["Integrity_Audit"], audit_headers,
                             "Populated by scripts/14_integrity_audit.py.")

    jair_headers = ["document", "status"]
    build_placeholder_sheet(wb["JAIR_Positioning"], jair_headers,
                             "See outputs/jair_presubmission/ for generated scaffolds.")

    tgt_headers = ["journal", "acronym", "rationale"]
    build_placeholder_sheet(wb["Target_Journal_Candidates"], tgt_headers,
                             "JAIR is the primary target per config/protocol.yaml.")

    checklist_headers = ["item", "status", "notes"]
    build_placeholder_sheet(wb["Submission_Readiness_Checklist"], checklist_headers,
                             "Populated at Phase 6 (final audit).")

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out_path)
    print(f"Wrote workbook with {len(wb.sheetnames)} sheets -> {out_path}")
    print("Sheets:", ", ".join(wb.sheetnames))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
